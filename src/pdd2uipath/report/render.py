"""Stage 8: hand-off report and traceability matrix."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

from pdd2uipath import __version__
from pdd2uipath.core.state import atomic_write_text
from pdd2uipath.design.models import DesignResult
from pdd2uipath.spec.models import ProcessSpec
from pdd2uipath.verify.checks import AuditResult, traceability_csv
from pdd2uipath.verify.diagnostics import GateVerdict


@dataclass(frozen=True)
class ReportContext:
    run_dir_windows: str
    project_dir_windows: str
    plan_rel: str
    executor: str
    agent_backend: str
    approver: str
    repair_rounds: int
    max_rounds: int
    pdd_filename: str
    pdd_sha256: str
    gate_passed: bool
    scaffold_commit: str | None
    final_commit: str | None
    agent_notes: list[str] = field(default_factory=list)  # final message of each session


def render_report(
    spec: ProcessSpec,
    design: DesignResult,
    audit: AuditResult,
    verdict: GateVerdict | None,
    ctx: ReportContext,
) -> str:
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines: list[str] = []
    a = lines.append
    a(f"# Hand-off report: {spec.meta.title}")
    a("")
    a(
        f"PDD {spec.meta.document_id} v{spec.meta.version} ({ctx.pdd_filename}, sha256 `{ctx.pdd_sha256[:16]}`) -> UiPath project `{design.project_name}`"
    )
    a("")
    a(f"- Generated by pdd2uipath {__version__} on {now}")
    a(f"- Project: `{ctx.project_dir_windows}`")
    a(f"- Plan: `{ctx.plan_rel}` (approved by {ctx.approver or 'n/a'})")
    a(f"- Executor: {ctx.executor}; authoring agent: {ctx.agent_backend}")
    a(
        f"- Template: {design.template.package_id or design.template.template_id} {design.template.package_version or ''}; target framework {design.target_framework}; expression language {design.expression_language}; UI capture {design.ui_capture}"
    )
    if ctx.scaffold_commit:
        a(
            f"- Git: pristine scaffold `{ctx.scaffold_commit[:10]}`"
            + (f", final `{ctx.final_commit[:10]}`" if ctx.final_commit else "")
        )
    a("")
    a("## Outcome")
    a("")
    if verdict is None:
        a("- Windows gate: not run")
    else:
        status = "PASSED" if verdict.passed else "FAILED"
        a(
            f"- Windows gate: **{status}** — {verdict.summary()} after {ctx.repair_rounds} repair round(s) (max {ctx.max_rounds})"
        )
    a(
        f"- Python audit: {'passed' if audit.passed else 'FAILED'}"
        + (": " + "; ".join(audit.problems()) if not audit.passed else "")
    )
    a(
        f"- Steps: {len(spec.steps)} in the PDD, {len(spec.steps) - len(audit.missing_steps)} traced to workflows; UI steps {', '.join(s.step_id for s in spec.ui_steps()) or 'none'}"
    )
    a(
        f"- `TODO Indicate` markers: {audit.todo_indicate_total} across {len(audit.todo_by_file)} file(s)"
    )
    confirm_total = sum(len(v) for v in audit.confirm_by_file.values())
    a(
        f"- `TODO Confirm` annotations (agent assumptions): {confirm_total} across {len(audit.confirm_by_file)} file(s)"
    )
    a("")
    a("## Decisions and rationale")
    a("")
    for d in design.decisions:
        refs = f" ({', '.join(d.source_refs)})" if d.source_refs else ""
        a(f"- **{d.topic}:** {d.choice} — {d.rationale}{refs}")
    if design.contradiction:
        a(f"- **Contradiction:** {design.contradiction.detail}")
    a("")
    a("## Open questions")
    a("")
    qs = list(design.blocking_questions) + list(design.nonblocking_questions)
    if not qs:
        a("- none")
    for q in qs:
        a(
            f"- {'[BLOCKING] ' if q.blocking else ''}{q.id} ({q.source_ref}): {q.text}"
            + (f" — owner: {q.owner}" if q.owner else "")
        )
    a("")
    a("## TODO Indicate (per file)")
    a("")
    if not audit.todo_by_file:
        a("- none found")
    for file, items in audit.todo_by_file.items():
        a(f"- `{file}`")
        for it in items:
            a(f"  - {it}")
    a("")
    a("## TODO Confirm (agent assumptions, per file)")
    a("")
    if not audit.confirm_by_file:
        a("- none found")
    for file, items in audit.confirm_by_file.items():
        a(f"- `{file}`")
        for it in items:
            a(f"  - {it}")
    a("")
    a("## Agent hand-off notes")
    a("")
    if not ctx.agent_notes:
        a("- none recorded")
    for i, note in enumerate(ctx.agent_notes, 1):
        a(f"### Session {i}")
        a("")
        a(note.strip())
        a("")
    a("## Orchestrator resources to create (names only)")
    a("")
    cv = design.config_values
    a(f"- Queue: `{cv.get('queue_name') or '(none)'}`")
    assets = [x for x in cv.get("assets", []) if x not in cv.get("credential_assets", [])]
    a(f"- Assets: {', '.join(f'`{x}`' for x in assets) or '(none)'}")
    a(
        f"- Credential assets: {', '.join(f'`{x}`' for x in cv.get('credential_assets', [])) or '(none)'}"
    )
    a("")
    a("## Validation")
    a("")
    if verdict is None:
        a("- not run")
    else:
        if verdict.errors:
            a(f"- {len(verdict.errors)} remaining error(s):")
            for diag in verdict.errors[:50]:
                a(
                    f"  - `{diag.file or '(project)'}`: {diag.message}"
                    + (f" [activity {diag.activity}]" if diag.activity else "")
                )
        else:
            a("- no errors other than the expected unconfigured-target ones")
        if verdict.expected_stub_errors:
            a(
                f"- {len(verdict.expected_stub_errors)} expected unconfigured-target error(s) on `TODO Indicate` activities (resolved by Indicate in Studio)"
            )
        if verdict.warnings:
            a(f"- {len(verdict.warnings)} warning(s) (non-blocking)")
    a("")
    a("## Traceability")
    a("")
    counts: dict[str, int] = {}
    for r in audit.rows:
        counts[r.status] = counts.get(r.status, 0) + 1
    a("- " + ", ".join(f"{k}: {v}" for k, v in sorted(counts.items())) if counts else "- no rows")
    a("- Full matrix: `traceability.csv` (step_id, pdd_ref, file, activity_display_name, status)")
    a("")
    a("## How to run")
    a("")
    a(
        f'1. Open the project in Studio Desktop: `pdd2uipath open-studio` (runs `uip rpa studio start --project-dir "{ctx.project_dir_windows}"` on the Windows side) or open `{ctx.project_dir_windows}\\project.json` from Studio.'
    )
    a(
        "2. For every `TODO Indicate` activity: select it, click **Indicate** on the live application, rename the activity."
    )
    a("3. Create the Orchestrator queue/assets listed above and fill the Config Assets section.")
    a(
        f'4. Re-run the gate: `pdd2uipath verify` (or `uip rpa build "{ctx.project_dir_windows}"`) until it is clean, then `uip rpa run --file-path Main.xaml --project-dir "{ctx.project_dir_windows}"` with test data.'
    )
    a("")
    a("## What a developer still has to do in Studio")
    a("")
    a(
        "- Indicate every placeholder target (see the TODO Indicate list) and refine selectors/anchors."
    )
    a(
        "- Review business-rule expressions and exception routing against the PDD; the agent implemented them from the plan, not from live screens."
    )
    a("- Resolve the open questions above with the process owner before go-live.")
    a(
        "- Confirm every `TODO Confirm` assumption and the blockers in the agent hand-off notes; they are the agent's own judgement calls, not PDD facts."
    )
    a(
        "- No Orchestrator deployment was performed: publish from Studio or your CI once the project runs end to end."
    )
    return "\n".join(lines) + "\n"


def write_outputs(run_dir: Path, report_text: str, audit: AuditResult) -> tuple[Path, Path]:
    report = run_dir / "report.md"
    csv_path = run_dir / "traceability.csv"
    atomic_write_text(report, report_text)
    atomic_write_text(csv_path, traceability_csv(audit.rows))
    return report, csv_path
