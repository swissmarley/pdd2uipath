class SurfaceMismatch(ExecutorError):
    """The live CLI lacks a verb or flag the pipeline needs."""


class UipCommands:
    """Build ``uip`` argument lists for canonical operations against a probed surface."""

    def __init__(self, surface: CliSurface | None = None, *, strict: bool = True) -> None:
        self.surface = surface or SNAPSHOT
        self.strict = strict

    def resolve(self, op: str) -> list[str]:
        paths = CANONICAL_OPS[op]
        for p in paths:
            if self.surface.has(p):
                return list(p)
        if self.strict and self.surface.verbs:
            raise SurfaceMismatch(
                f"the probed uip CLI ({self.surface.uip_version}) exposes none of "
                f"{[' '.join(p) for p in paths]} for '{op}'. Re-run `pdd2uipath doctor` "
                "or update @uipath/cli."
            )
        return list(paths[0])

    def _check_flags(self, path: list[str], flags: Sequence[str]) -> None:
        known = self.surface.flags_for(path)
        if not known or not self.strict:
            return
        missing = [f for f in flags if f not in known]
        if missing:
            raise SurfaceMismatch(
                f"`uip {' '.join(path)}` does not accept {missing} on this CLI "
                f"({self.surface.uip_version}); known flags: {known}"
            )

    def _argv(
        self,
        op: str,
        *pairs: tuple[str, str | None],
        flags: Sequence[str] = (),
        positional: Sequence[str] = (),
    ) -> list[str]:
        path = self.resolve(op)
        used = [f for f, v in pairs if v is not None] + list(flags)
        self._check_flags(path, [*used, "--output"])
        argv = [*path, *positional]
        for f, v in pairs:
            if v is not None:
                argv += [f, v]
        argv += list(flags)
        argv += ["--output", "json"]
        return argv

    # -- canonical operations ------------------------------------------------
    def templates_search(
        self, query: str, *, limit: int | None = None, include_prerelease: bool = False
    ) -> list[str]:
        return self._argv(
            "templates_search",
            ("--query", query),
            ("--limit", str(limit) if limit else None),
            flags=["--include-prerelease"] if include_prerelease else [],
        )

    def init(
        self,
        *,
        name: str,
        location_windows: str,
        target_framework: str,
        expression_language: str,
        description: str = "",
        template_id: str | None = None,
        template_package_id: str | None = None,
        template_package_version: str | None = None,
    ) -> list[str]:
        if template_package_id is None and template_id is None:
            template_id = "BlankTemplate"
        return self._argv(
            "init",
            ("--name", name),
            ("--location", location_windows),
            ("--template-id", template_id if template_package_id is None else None),
            ("--template-package-id", template_package_id),
            ("--template-package-version", template_package_version),
            ("--target-framework", target_framework),
            ("--expression-language", expression_language),
            ("--description", description or None),
        )

    def restore(self, project_windows: str) -> list[str]:
        return self._argv("restore", positional=[project_windows])

    def packages_versions(
        self, package_id: str, project_windows: str | None, *, include_prerelease: bool = False
    ) -> list[str]:
        return self._argv(
            "packages_versions",
            ("--package-id", package_id),
            ("--project-dir", project_windows),
            flags=["--include-prerelease"] if include_prerelease else [],
        )

    def packages_install(
        self, packages: Sequence[tuple[str, str | None]], project_windows: str
    ) -> list[str]:
        path = self.resolve("packages_install")
        self._check_flags(path, ["--packages", "--project-dir", "--output"])
        argv = list(path)
        for pid, ver in packages:
            argv += ["--packages", f"id={pid},version={ver}" if ver else f"id={pid}"]
        argv += ["--project-dir", project_windows, "--output", "json"]
        return argv

    def activities_find(
        self, query: str, project_windows: str | None, *, limit: int = 5
    ) -> list[str]:
        return self._argv(
            "activities_find",
            ("--query", query),
            ("--limit", str(limit)),
            ("--project-dir", project_windows),
        )

    def validate(
        self, project_windows: str, file_rel: str | None = None, *, min_severity: str = "error"
    ) -> list[str]:
        return self._argv(
            "validate",
            ("--file-path", file_rel),
            ("--min-severity", min_severity),
            ("--project-dir", project_windows),
        )

    def build(self, project_windows: str) -> list[str]:
        return self._argv("build", positional=[project_windows])

    def studio_start(self, project_windows: str) -> list[str]:
        return self._argv("studio_start", ("--project-dir", project_windows))

    def instances_list(self) -> list[str]:
        return self._argv("instances_list")

    def login_status(self) -> list[str]:
        return self._argv("login_status")

    @staticmethod
    def job(argv: list[str], cwd: str, *, timeout_s: float = 900.0, label: str = "") -> Job:
        return Job(argv=argv, cwd=cwd, timeout_s=timeout_s, label=label)
