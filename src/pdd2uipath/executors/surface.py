"""Probe the live ``uip`` CLI surface and adapt canonical operations to it.

The adapter never hard-codes verb spellings: ``docs/cli-surface.md`` is generated by
``doctor`` from ``uip --help`` / ``uip rpa <verb> --help`` on the Windows side, and
``UipCommands`` resolves each canonical operation (e.g. *validate*) to whichever verb
the live CLI exposes (``rpa validate`` today, ``rpa get-errors`` on older builds).
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path

from pydantic import BaseModel, Field

from pdd2uipath.executors.base import Executor, ExecutorError, Job, UipResult

#: canonical operation -> candidate verb paths, first match in the live surface wins.
CANONICAL_OPS: dict[str, list[list[str]]] = {
    "templates_search": [["rpa", "templates", "search"], ["rpa", "search-templates"]],
    "init": [["rpa", "init"], ["rpa", "create-project"]],
    "restore": [["rpa", "restore"]],
    "packages_versions": [["rpa", "packages", "versions"]],
    "packages_install": [["rpa", "packages", "install"], ["rpa", "add-dependency"]],
    "activities_find": [["rpa", "activities", "find"], ["rpa", "find-activities"]],
    "validate": [["rpa", "validate"], ["rpa", "get-errors"]],
    "build": [["rpa", "build"]],
    "analyze": [["rpa", "analyze"]],
    "studio_start": [["rpa", "studio", "start"], ["rpa", "start-studio"]],
    "instances_list": [["rpa", "instances", "list"]],
    "login_status": [["login", "status"]],
}

_FLAG_RE = re.compile(r"(?<![\w-])(--?[a-z][a-z0-9-]*)")
_BOX_LINE_RE = re.compile(r"^\s*[│|]\s{1,3}([a-z][a-z0-9-]+)\s{2,}[^\s│|]")
_UNKNOWN_RE = re.compile(r"unknown command|invalid_argument|is not a .*command", re.I)


class VerbSpec(BaseModel):
    path: list[str]
    usage: str = ""
    flags: list[str] = Field(default_factory=list)
    subcommands: list[str] = Field(default_factory=list)
    positional: list[str] = Field(default_factory=list)

    @property
    def key(self) -> str:
        return " ".join(self.path)


class CliSurface(BaseModel):
    uip_version: str = ""
    probed_at: str = ""
    side: str = ""
    top_commands: list[str] = Field(default_factory=list)
    rpa_commands: list[str] = Field(default_factory=list)
    verbs: dict[str, VerbSpec] = Field(default_factory=dict)
    notes: list[str] = Field(default_factory=list)

    def has(self, path: Sequence[str]) -> bool:
        return " ".join(path) in self.verbs

    def flags_for(self, path: Sequence[str]) -> list[str]:
        spec = self.verbs.get(" ".join(path))
        return spec.flags if spec else []


class ParsedHelp(BaseModel):
    usage: str = ""
    flags: list[str] = Field(default_factory=list)
    subcommands: list[str] = Field(default_factory=list)
    positional: list[str] = Field(default_factory=list)


def _section(text: str, title: str) -> str:
    """Return the content of a ``┌─ Title ───┐ ... └───┘`` box (or ``Title:`` block)."""
    m = re.search(rf"[┌+]─+\s*{re.escape(title)}\b[^\n]*\n(.*?)(?:\n\s*[└+]─)", text, re.S)
    return m.group(1) if m else ""


def parse_help(text: str) -> ParsedHelp:
    usage_box = _section(text, "Usage")
    usage = " ".join(
        line.strip().strip("│|").strip() for line in usage_box.splitlines() if line.strip()
    ).strip()
    flags = sorted({f for f in _FLAG_RE.findall(text) if f.startswith("--") or len(f) == 2})
    subcommands = [
        m.group(1)
        for m in (_BOX_LINE_RE.match(line) for line in _section(text, "Commands").splitlines())
        if m
    ]
    positional = [
        m.group(1)
        for m in (_BOX_LINE_RE.match(line) for line in _section(text, "Arguments").splitlines())
        if m
    ]
    return ParsedHelp(usage=usage, flags=flags, subcommands=subcommands, positional=positional)


def _help_text(result: UipResult) -> str:
    return result.stdout + "\n" + result.stderr


def probe_surface(executor: Executor, *, timeout_s: float = 120.0) -> CliSurface:
    """Probe ``uip`` on the executor's side. Never raises on missing verbs."""
    surface = CliSurface(
        probed_at=datetime.now(UTC).isoformat(timespec="seconds"), side=executor.name
    )
    ver = executor.run(["--version"], timeout_s=timeout_s)
    surface.uip_version = ver.stdout.strip().splitlines()[-1] if ver.stdout.strip() else ver.message
    top = executor.run(["--help"], timeout_s=timeout_s)
    surface.top_commands = parse_help(_help_text(top)).subcommands
    rpa = executor.run(["rpa", "--help"], timeout_s=timeout_s)
    rpa_text = _help_text(rpa)
    if rpa.exit_code != 0 and _UNKNOWN_RE.search(rpa_text):
        surface.notes.append(
            "`uip rpa` is not installed on this side (uip tools install @uipath/rpa-tool)"
        )
        return surface
    surface.rpa_commands = parse_help(rpa_text).subcommands
    candidates: list[list[str]] = []
    for paths in CANONICAL_OPS.values():
        for p in paths:
            if p not in candidates:
                candidates.append(p)
    for path in candidates:
        if path[0] == "rpa" and surface.rpa_commands and path[1] not in surface.rpa_commands:
            continue
        res = executor.run([*path, "--help"], timeout_s=timeout_s)
        text = _help_text(res)
        if res.exit_code != 0 and _UNKNOWN_RE.search(text):
            continue
        parsed = parse_help(text)
        if not parsed.usage and not parsed.flags:
            continue
        surface.verbs[" ".join(path)] = VerbSpec(
            path=list(path),
            usage=parsed.usage,
            flags=parsed.flags,
            subcommands=parsed.subcommands,
            positional=parsed.positional,
        )
    return surface


def render_markdown(surface: CliSurface) -> str:
    lines = [
        "# uip CLI surface (probed)",
        "",
        f"- uip version: `{surface.uip_version}`",
        f"- probed at: {surface.probed_at} on `{surface.side}`",
        f"- top-level commands: {', '.join(f'`{c}`' for c in surface.top_commands) or '(none parsed)'}",
        f"- `uip rpa` commands: {', '.join(f'`{c}`' for c in surface.rpa_commands) or '(none parsed)'}",
        "",
        "The command adapter (`pdd2uipath.executors.surface.UipCommands`) resolves canonical",
        "operations against this table; a missing flag or verb raises `SurfaceMismatch`",
        "instead of guessing.",
        "",
        "| canonical op | resolved verb |",
        "|---|---|",
    ]
    for op, paths in CANONICAL_OPS.items():
        resolved = next((" ".join(p) for p in paths if surface.has(p)), "(missing)")
        lines.append(f"| `{op}` | `uip {resolved}` |")
    lines.append("")
    for key, spec in surface.verbs.items():
        lines.append(f"## `uip {key}`")
        lines.append("")
        if spec.usage:
            lines.append(f"Usage: `{spec.usage}`")
            lines.append("")
        if spec.positional:
            lines.append(f"Positional: {', '.join(f'`{p}`' for p in spec.positional)}")
            lines.append("")
        lines.append("Flags: " + ", ".join(f"`{f}`" for f in spec.flags))
        lines.append("")
    if surface.notes:
        lines.append("## Notes")
        lines.extend(f"- {n}" for n in surface.notes)
        lines.append("")
    return "\n".join(lines)


def save_surface(surface: CliSurface, json_path: Path, md_path: Path | None = None) -> None:
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(surface.model_dump_json(indent=2), encoding="utf-8")
    if md_path is not None:
        md_path.parent.mkdir(parents=True, exist_ok=True)
        md_path.write_text(render_markdown(surface), encoding="utf-8")


def load_surface(json_path: Path) -> CliSurface | None:
    if not json_path.is_file():
        return None
    try:
        return CliSurface.model_validate_json(json_path.read_text(encoding="utf-8"))
    except ValueError:
        return None


